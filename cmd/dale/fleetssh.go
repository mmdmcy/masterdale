package main

// fleet ssh automates passwordless SSH between fleet devices. It reuses the
// masterdale agent's /v1/exec API on each target, so no third-party SSH
// libraries are involved: keys are generated with crypto/ed25519 and stored
// in OpenSSH's native format.

